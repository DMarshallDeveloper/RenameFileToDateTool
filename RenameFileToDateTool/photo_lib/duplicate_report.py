def _year_from_relpath(relpath: str) -> str:
    """Extract a year bucket from a relative path.

    Folder hierarchy wins when available — preserves the master library's
    ``BUNDLED_EARLY_FOLDER`` convention verbatim ("2000 - 2010" stays as-is).
    For flat layouts (pilot dest, or any file directly under the root) the
    year is derived from the canonical ``YYYY-`` prefix on the filename
    itself; years in the bundled-early range collapse to
    ``BUNDLED_EARLY_FOLDER`` so flat and nested layouts agree.
    """
    parts = relpath.replace("\\", "/").split("/")
    if len(parts) >= 2:
        first = parts[0]
        if first[:4].isdigit():
            return first
    basename = parts[-1]
    year_prefix = basename[:4]
    if year_prefix.isdigit():
        year = int(year_prefix)
        if year in _BUNDLED_EARLY_YEARS:
            return BUNDLED_EARLY_FOLDER
        return year_prefix
    return "(no year)"


def render_singletons_html_report(
    singletons: Iterable[FileFingerprint],
    library_root: str,
    source_labels: dict[str, str] | None = None,
    thumbnails: dict[str, str | None] | None = None,
) -> str:
    """Render an HTML report of files that weren't grouped as duplicates.

    Useful for spotting files that exist in only one source — after a combine
    of master + takeout, a singleton is either a genuine one-of-a-kind photo
    OR a file whose perceptual signature was too far from any sibling to
    cluster at the chosen threshold.

    Grouped by year folder, thumbnails inlined just like the dupes report.
    ``source_labels`` is the provenance map from ``SourceManifest.all_entries``
    — when supplied, each card carries an ``src: <label>`` badge so a
    singleton's source library is visible at a glance.
    """
    by_year: dict[str, list[FileFingerprint]] = {}
    for fingerprint in singletons:
        relpath = os.path.relpath(fingerprint.path, library_root)
        year = _year_from_relpath(relpath)
        by_year.setdefault(year, []).append(fingerprint)

    parts = [_HTML_HEAD]
    parts.append(
        f'<h1>Singletons — files not in any duplicate group — '
        f'{html.escape(os.path.basename(library_root) or library_root)}</h1>'
    )
    total = sum(len(items) for items in by_year.values())
    parts.append(
        f'<div class="summary">'
        f'  {total} singleton files across {len(by_year)} year buckets. '
        f'  These have no detected duplicate at the current pHash threshold — '
        f'  they may be one-of-a-kind originals OR cases where the dedup missed.'
        f'</div>'
    )
    for year in sorted(by_year.keys()):
        items = sorted(by_year[year], key=lambda fp: fp.path)
        cards = "\n".join(
            _render_card(
                fingerprint, position=1,
                library_root=library_root,
                source_labels=source_labels,
                thumbnails=thumbnails,
            )
            for fingerprint in items
        )
        parts.append(
            f'<div class="group">'
            f'  <div class="group-header" style="border-left-color: #555">'
            f'    <span class="tier-badge" style="background: #555">{html.escape(year)}</span>'
            f'    <span class="count">{len(items)} singletons</span>'
            f'  </div>'
            f'  <div class="cards">{cards}</div>'
            f'</div>'
        )
    parts.append("</body></html>")
    return "\n".join(parts)


def _bucket_year(fingerprint: FileFingerprint, library_root: str) -> str:
    return _year_from_relpath(os.path.relpath(fingerprint.path, library_root))


def _extension_of(fingerprint: FileFingerprint) -> str:
    ext = os.path.splitext(fingerprint.path)[1].lstrip(".").lower()
    return ext or "(none)"


def _render_stats_table(
    headers: tuple[str, ...],
    rows: list[tuple],
    total_row: tuple | None = None,
) -> str:
    """Render a stats table. ``rows`` / ``total_row`` are tuples whose length
    matches ``headers``. Cells after the first are treated as numeric and
    right-aligned.
    """
    head_cells = "".join(f"<th>{html.escape(h)}</th>" for h in headers)
    body_cells = []
    for row in rows:
        cells = [f"<td>{html.escape(str(row[0]))}</td>"]
        cells += [f'<td class="num">{html.escape(str(value))}</td>' for value in row[1:]]
        body_cells.append("<tr>" + "".join(cells) + "</tr>")
    total_html = ""
    if total_row is not None:
        cells = [f"<td>{html.escape(str(total_row[0]))}</td>"]
        cells += [f'<td class="num">{html.escape(str(value))}</td>' for value in total_row[1:]]
        total_html = '<tr class="total">' + "".join(cells) + "</tr>"
    return (
        '<table class="stats">'
        f'<thead><tr>{head_cells}</tr></thead>'
        f'<tbody>{"".join(body_cells)}{total_html}</tbody>'
        '</table>'
    )


def render_stats_html_report(
    fingerprints: Iterable[FileFingerprint],
    groups: Iterable[DuplicateGroup],
    library_root: str,
    source_labels: dict[str, str] | None = None,
) -> str:
    """Library overview: counts and sizes by year / extension / media kind,
    plus a duplicate-group rollup showing how many bytes the manual review
    could plausibly reclaim (sum of loser sizes across all groups).

    When ``source_labels`` is provided (typically from the combine manifest),
    an additional "By source" table breaks files down by their source library.
    """
    fingerprints = list(fingerprints)
    groups = list(groups)

    total_files = len(fingerprints)
    total_bytes = sum(fp.size for fp in fingerprints)

    by_year: dict[str, list[FileFingerprint]] = {}
    by_extension: dict[str, list[FileFingerprint]] = {}
    by_media_kind: dict[str, list[FileFingerprint]] = {}
    by_source: dict[str, list[FileFingerprint]] = {}
    for fingerprint in fingerprints:
        by_year.setdefault(_bucket_year(fingerprint, library_root), []).append(fingerprint)
        by_extension.setdefault(_extension_of(fingerprint), []).append(fingerprint)
        by_media_kind.setdefault(fingerprint.media_kind, []).append(fingerprint)
        if source_labels:
            label = source_labels.get(os.path.normpath(fingerprint.path), "(unknown)")
            by_source.setdefault(label, []).append(fingerprint)

    groups_by_tier: dict[int, list[DuplicateGroup]] = {1: [], 2: [], 3: []}
    files_in_groups = 0
    loser_bytes = 0
    for group in groups:
        groups_by_tier.setdefault(group.tier, []).append(group)
        files_in_groups += len(group.fingerprints)
        ranked = group.ranked()
        loser_bytes += sum(fp.size for fp in ranked[1:])

    parts = [_HTML_HEAD]
    parts.append(
        f'<h1>Library statistics — '
        f'{html.escape(os.path.basename(library_root) or library_root)}</h1>'
    )
    parts.append(
        f'<div class="summary">'
        f'  <b>{total_files}</b> files · <b>{_format_size(total_bytes)}</b> · '
        f'  {len(by_year)} year buckets · '
        f'  {len(by_extension)} extensions · '
        f'  {len(groups)} duplicate groups'
        f'</div>'
    )

    parts.append("<h2>By year</h2>")
    year_rows = [
        (year, len(items), _format_size(sum(fp.size for fp in items)))
        for year, items in sorted(by_year.items())
    ]
    parts.append(_render_stats_table(
        ("Year", "Files", "Size"),
        year_rows,
        ("Total", total_files, _format_size(total_bytes)),
    ))

    parts.append("<h2>By extension</h2>")
    extension_rows = []
    for ext, items in sorted(by_extension.items(), key=lambda kv: -sum(fp.size for fp in kv[1])):
        bytes_for_ext = sum(fp.size for fp in items)
        pct = (bytes_for_ext / total_bytes * 100) if total_bytes else 0
        extension_rows.append((
            ext, len(items), _format_size(bytes_for_ext), f"{pct:.1f}%",
        ))
    parts.append(_render_stats_table(
        ("Extension", "Files", "Size", "% bytes"),
        extension_rows,
        ("Total", total_files, _format_size(total_bytes), "100.0%"),
    ))

    parts.append("<h2>By media kind</h2>")
    media_rows = [
        (kind, len(items), _format_size(sum(fp.size for fp in items)))
        for kind, items in sorted(by_media_kind.items())
    ]
    parts.append(_render_stats_table(
        ("Media kind", "Files", "Size"),
        media_rows,
    ))

    if by_source:
        parts.append("<h2>By source library</h2>")
        source_rows = []
        for label, items in sorted(by_source.items(), key=lambda kv: -len(kv[1])):
            bytes_for_source = sum(fp.size for fp in items)
            pct = (len(items) / total_files * 100) if total_files else 0
            source_rows.append((
                label, len(items), _format_size(bytes_for_source), f"{pct:.1f}%",
            ))
        parts.append(_render_stats_table(
            ("Source", "Files", "Size", "% files"),
            source_rows,
            ("Total", total_files, _format_size(total_bytes), "100.0%"),
        ))

    parts.append("<h2>Duplicates</h2>")
    tier_rows = []
    for tier in (1, 2, 3):
        tier_groups = groups_by_tier.get(tier, [])
        label, blurb, _color = TIER_LABELS[tier]
        files_at_tier = sum(len(g.fingerprints) for g in tier_groups)
        tier_rows.append((f"{label} — {blurb}", len(tier_groups), files_at_tier))
    parts.append(_render_stats_table(
        ("Tier", "Groups", "Files"),
        tier_rows,
        ("Total", len(groups), files_in_groups),
    ))
    parts.append(
        f'<div class="summary">'
        f'  Manual review of the {len(groups)} groups could reclaim up to '
        f'  <b>{_format_size(loser_bytes)}</b> '
        f'  (sum of sizes of all non-winners). Singletons: <b>{total_files - files_in_groups}</b>.'
        f'</div>'
    )

    parts.append("</body></html>")
    return "\n".join(parts)


def render_html_report(
    groups: Iterable[DuplicateGroup],
    library_root: str,
    source_labels: dict[str, str] | None = None,
    thumbnails: dict[str, str | None] | None = None,
) -> str:
    """Return a complete HTML document string for the given duplicate groups.

    ``source_labels`` (from ``SourceManifest.all_entries``) is optional —
    when present, each card carries a ``src: <label>`` badge showing the
    library the file came from.

    ``thumbnails`` is an optional ``{path: data_uri}`` cache from
    ``precompute_thumbnails``. When given, no synchronous thumbnail
    generation happens here — useful for big libraries where the
    parallel precompute is much faster than the sequential fallback.
    """
    materialized = list(groups)
    groups_by_tier = {1: [], 2: [], 3: []}
    for group in materialized:
        groups_by_tier.setdefault(group.tier, []).append(group)
    total_files = sum(len(group.fingerprints) for group in materialized)
    parts = [_HTML_HEAD]
    parts.append(
        f'<h1>Duplicate review — '
        f'{html.escape(os.path.basename(library_root) or library_root)}</h1>'
    )
    parts.append(
        f'<div class="summary">'
        f'  {len(materialized)} groups, {total_files} files. '
        f'  Tier 1: {len(groups_by_tier[1])}; '
        f'  Tier 2: {len(groups_by_tier[2])}; '
        f'  Tier 3: {len(groups_by_tier[3])}.'
        f'</div>'
    )
    sorted_groups = sorted(materialized, key=lambda g: (g.tier, -len(g.fingerprints)))
    for group in sorted_groups:
        parts.append(_render_group(
            group, library_root,
            source_labels=source_labels, thumbnails=thumbnails,
        ))
    parts.append("</body></html>")
    return "\n".join(parts)
