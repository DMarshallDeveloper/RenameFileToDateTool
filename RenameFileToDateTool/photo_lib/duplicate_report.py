"""HTML reports for the dedup workflow.

Three self-contained HTML documents, all generated by ``find_duplicate_photos
report``:

  ``render_html_report``           — side-by-side duplicate review (thumbnails
                                     + tier badges) for manual delete-in-Explorer.
  ``render_singletons_html_report``— files that didn't cluster with anything,
                                     grouped by year. Catches misses.
  ``render_stats_html_report``     — library overview: totals, by-year /
                                     by-extension / by-media-kind tables, and
                                     a duplicate-bytes-reclaimable summary.

Thumbnails are inlined as base64 so each file is portable.
"""
from __future__ import annotations

import base64
import html
import io
import logging
import os
from typing import Iterable

from PIL import Image

from photo_lib.config import BUNDLED_EARLY_FOLDER, BUNDLED_EARLY_YEAR_RANGE
from photo_lib.duplicate_finder import DuplicateGroup, FileFingerprint
from photo_lib.filename_pattern import CANONICAL_FILENAME_PARTS_RE

_BUNDLED_EARLY_YEARS = set(range(*BUNDLED_EARLY_YEAR_RANGE))

logger = logging.getLogger("photo_lib")

THUMBNAIL_MAX_PX = 240
TIER_LABELS = {
    1: ("Tier 1", "byte-identical file", "#1f7a1f"),
    2: ("Tier 2", "identical pixels", "#1f5a7a"),
    3: ("Tier 3", "perceptually identical", "#7a3f1f"),
}


def _thumbnail_data_uri(path: str, max_px: int = THUMBNAIL_MAX_PX) -> str | None:
    try:
        with Image.open(path) as image:
            image = image.convert("RGB")
            image.thumbnail((max_px, max_px))
            buffer = io.BytesIO()
            image.save(buffer, format="JPEG", quality=78)
            encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
            return f"data:image/jpeg;base64,{encoded}"
    except Exception as exc:
        logger.debug("Thumbnail failed for %s: %s", path, exc)
        return None


def precompute_thumbnails(
    paths: list[str],
    max_workers: int = 8,
    log_every: int = 1000,
) -> dict[str, str | None]:
    """Generate thumbnail data URIs for ``paths`` in parallel.

    On an external HDD the sequential thumbnail loop was the report's
    bottleneck — ~150-300ms per file × 30k = 1.5 hours wall-clock with
    no progress visibility. PIL's image decode releases the GIL, so a
    small thread pool cuts wall-clock by 5-8× and we can emit ticks so
    the operator knows roughly where it is.
    """
    from concurrent.futures import ThreadPoolExecutor, as_completed
    total = len(paths)
    if total == 0:
        return {}
    logger.info("Generating %d thumbnails (%d workers in parallel)...",
                total, max_workers)
    out: dict[str, str | None] = {}
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_path = {
            executor.submit(_thumbnail_data_uri, p): p for p in paths
        }
        for index, future in enumerate(as_completed(future_to_path), start=1):
            path = future_to_path[future]
            try:
                out[path] = future.result()
            except Exception as exc:
                logger.debug("Thumbnail failed for %s: %s", path, exc)
                out[path] = None
            if index % log_every == 0:
                logger.info("  thumbnails: %d / %d", index, total)
    logger.info("  thumbnails: %d / %d (done)", total, total)
    return out


def _format_size(byte_count: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if byte_count < 1024:
            return f"{byte_count:.1f} {unit}" if unit != "B" else f"{byte_count} B"
        byte_count /= 1024
    return f"{byte_count:.1f} TB"


def _source_label_for(
    fingerprint: FileFingerprint,
    source_labels: dict[str, str] | None,
) -> str | None:
    if not source_labels:
        return None
    return source_labels.get(os.path.normpath(fingerprint.path))


def _render_card(
    fingerprint: FileFingerprint,
    position: int,
    library_root: str,
    source_labels: dict[str, str] | None = None,
    thumbnails: dict[str, str | None] | None = None,
) -> str:
    # Prefer the precomputed thumbnail cache if the caller went through
    # precompute_thumbnails(). Falls back to lazy single-threaded
    # generation otherwise (preserves the previous behavior for callers
    # that haven't been updated).
    if thumbnails is not None and fingerprint.path in thumbnails:
        thumbnail = thumbnails[fingerprint.path]
    else:
        thumbnail = _thumbnail_data_uri(fingerprint.path)
    thumb_html = (
        f'<img src="{thumbnail}" />'
        if thumbnail
        else '<div class="no-thumb">no preview</div>'
    )
    relpath = os.path.relpath(fingerprint.path, library_root)
    dimensions = (
        f"{fingerprint.width}×{fingerprint.height}"
        if fingerprint.width and fingerprint.height
        else "?"
    )
    is_winner = position == 0
    badge = '<span class="winner">winner</span>' if is_winner else ""
    source_label = _source_label_for(fingerprint, source_labels)
    source_html = (
        f'<span class="src-badge" title="source library">'
        f'src: {html.escape(source_label)}</span>'
        if source_label else ""
    )
    return (
        f'<div class="card{" winner-card" if is_winner else ""}">'
        f'  <div class="thumb">{thumb_html}</div>'
        f'  <div class="meta">'
        f'    {badge}{source_html}'
        f'    <div class="path">{html.escape(relpath)}</div>'
        f'    <div class="stats">{dimensions} · {_format_size(fingerprint.size)}</div>'
        f'  </div>'
        f'</div>'
    )


def _is_cross_date_group(group: DuplicateGroup) -> bool:
    """A group spans different timestamps when its canonical members don't all
    share the same ``<base>``. Non-canonical members are ignored (they don't
    contribute a base anyway). A group with 0-1 distinct bases is NOT
    cross-date.
    """
    bases: set[str] = set()
    for fingerprint in group.fingerprints:
        match = CANONICAL_FILENAME_PARTS_RE.match(os.path.basename(fingerprint.path))
        if match:
            bases.add(match.group("base"))
    return len(bases) >= 2


def _render_group(
    group: DuplicateGroup,
    library_root: str,
    source_labels: dict[str, str] | None = None,
    thumbnails: dict[str, str | None] | None = None,
) -> str:
    label, blurb, color = TIER_LABELS[group.tier]
    cards = "\n".join(
        _render_card(fingerprint, position, library_root,
                     source_labels=source_labels, thumbnails=thumbnails)
        for position, fingerprint in enumerate(group.ranked())
    )
    cross_date_badge = (
        '<span class="cross-date-badge" '
        'title="Group members have different timestamps — pick which date is the true one">'
        'cross-date</span>'
        if _is_cross_date_group(group) else ""
    )
    return (
        f'<div class="group">'
        f'  <div class="group-header" style="border-left-color: {color}">'
        f'    <span class="tier-badge" style="background: {color}">{label}</span>'
        f'    <span class="tier-blurb">{blurb}</span>'
        f'    {cross_date_badge}'
        f'    <span class="count">{len(group.fingerprints)} files</span>'
        f'  </div>'
        f'  <div class="cards">{cards}</div>'
        f'</div>'
    )


